class Page:
    def __init__(self, pdf, title, sub='', foot=''):
        self.fig = plt.figure(figsize=(8.27, 11.69))
        self.pdf, self.foot = pdf, foot
        self.y = 0.952
        self.fig.text(0.08, self.y, title, fontsize=17.5, fontweight='bold', color=INK)
        self.y -= 0.026
        if sub:
            self.fig.text(0.08, self.y, sub, fontsize=9.3, color=MUTED)
            self.y -= 0.016
        self.fig.lines.append(plt.Line2D([0.08, 0.92], [self.y, self.y], color=INK,
                                         lw=1.5, transform=self.fig.transFigure))
        self.y -= 0.028

    def h(self, t, color=TEAL, size=12):
        self.y -= 0.007
        self.fig.text(0.08, self.y, t, fontsize=size, fontweight='bold', color=color)
        self.y -= 0.022

    def p(self, t, size=9.5, color=INK, gap=0.0165):
        for line in t.split('\n'):
            self.fig.text(0.08, self.y, line, fontsize=size, color=color)
            self.y -= gap
        self.y -= 0.005

    def box(self, t, color=TEAL, size=9.8):
        """강조 문단. 왼쪽에 색 막대."""
        n = len(t.split('\n'))
        top = self.y + 0.011
        for line in t.split('\n'):
            self.fig.text(0.098, self.y, line, fontsize=size, color=INK,
                          fontweight='bold')
            self.y -= 0.0175
        self.fig.lines.append(plt.Line2D([0.081, 0.081], [top, self.y + 0.012],
                                         color=color, lw=3,
                                         transform=self.fig.transFigure))
        self.y -= 0.008

    def table(self, head, rows, widths, size=8.8):
        xs, x = [], 0.08
        for w in widths:
            xs.append(x); x += w
        for c, xx in zip(head, xs):
            self.fig.text(xx, self.y, c, fontsize=size, fontweight='bold', color=MUTED)
        self.y -= 0.005
        self.fig.lines.append(plt.Line2D([0.08, x], [self.y, self.y], color='#c9d2d0',
                                         lw=0.8, transform=self.fig.transFigure))
        self.y -= 0.0145
        for r in rows:
            for c, xx in zip(r, xs):
                b = c.startswith('*')
                self.fig.text(xx, self.y, c.lstrip('*'), fontsize=size, color=INK,
                              fontweight='bold' if b else 'normal')
            self.y -= 0.0155
        self.y -= 0.007

    def note(self, t, color=WARM, size=8.9):
        for line in t.split('\n'):
            self.fig.text(0.08, self.y, line, fontsize=size, color=color)
            self.y -= 0.0155
        self.y -= 0.005

    def close(self):
        if self.foot:
            self.fig.text(0.08, 0.035, self.foot, fontsize=8, color=MUTED)
        self.pdf.savefig(self.fig)
        if os.environ.get('PDF_PNG'):
            Page._n = getattr(Page, '_n', 0) + 1
            self.fig.savefig(os.path.join(OUT, 'preview_%d.png' % Page._n), dpi=105,
                             facecolor='white')
        plt.close(self.fig)


